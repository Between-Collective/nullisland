const BY_ID = new Map(PLACES.map((p) => [p.id, p]));

export function getPlace(id: string): Place | undefined {
  return BY_ID.get(id);
}

export function placesOfKind(kind: PlaceKind): Place[] {
  return PLACES.filter((p) => p.kind === kind);
}

/** Every name this place answers to, canonical first. */
export function allNames(place: Place): string[] {
  return [place.name, ...(place.aliases ?? []).map((a) => a.name)];
}

/** An alias of a particular kind, when this place has one. */
export function aliasOfKind(place: Place, kind: AliasKind): Alias | undefined {
  return place.aliases?.find((a) => a.kind === kind);
}

/** The chain outwards: a venue, then its city, then its country. */
export function containers(place: Place): Place[] {
  const chain: Place[] = [];
  let current = place.within ? BY_ID.get(place.within) : undefined;
  // Bounded rather than while(true): a bad `within` cycle in the data would
  // otherwise hang the generator instead of producing a wrong term.
  for (let depth = 0; current && depth < 4; depth++) {
    chain.push(current);
    current = current.within ? BY_ID.get(current.within) : undefined;
  }
  return chain;
}

