/**
 * The gazetteer a generated search term is built from — and asserted against.
 *
 * A list of query strings is not a test fixture. "Devices in Cambridge" is only
 * useful if something beside it says which Cambridge, where it is, and that
 * there are two of them; otherwise you are eyeballing results rather than
 * asserting on them. So every place here carries the answer a geocoder is
 * supposed to return, and the reason it usually doesn't: the other place with
 * the same name, the name the locals use, the name it had until 1995, and the
 * bounding box that is four times bigger than anyone expects.
 *
 * Coordinates are real and centroids are approximate — a city is not a point,
 * and the bbox is the thing you filter on anyway. Nothing in here is invented:
 * an invented ambiguity would fail a geocoder for a reason no user will ever
 * reproduce.
 */

export type PlaceKind = "venue" | "city" | "region" | "country";

export type AliasKind =
  /** What English calls it: Munich, Florence, Lisbon. */
  | "exonym"
  /** What it calls itself: München, Firenze, Lisboa. */
  | "endonym"
  /** NYC, UAE, CDMX. */
  | "abbreviation"
  /** The name it used to have, still typed by half your users. */
  | "former"
  /** Not the real name, but what people say. Holland for the Netherlands. */
  | "colloquial"
  /** An airport or station code standing in for the place. */
  | "code";

export interface Alias {
  name: string;
  kind: AliasKind;
}

export interface Place {
  id: string;
  /** The canonical name, spelled the way a geocoder should return it. */
  name: string;
  kind: PlaceKind;
  lon: number;
  lat: number;
  /** [minLon, minLat, maxLon, maxLat]. A venue still gets one, a block across. */
  bbox: [number, number, number, number];
  /** ISO 3166-1 alpha-2. */
  country: string;
  /** The place this one sits inside — a venue's city, a city's country. */
  within?: string;
  /** Other names for the same place. Every one of these is really used. */
  aliases?: Alias[];
  /**
   * Somewhere else with this name. The reason "Cambridge" is not an answer, and
   * the reason a geocoder that returns one result without saying so is wrong.
   */
  ambiguousWith?: string[];
  /** Rough population, which is how a ranker breaks the tie. */
  population?: number;
  /** Something true about this place that breaks a filter written for it. */
  note?: string;
}

/** A venue sits on a point; the box is roughly the site around it. */
function site(lon: number, lat: number, km = 0.4): [number, number, number, number] {
  const dLat = km / 111;
  const dLon = km / (111 * Math.max(0.1, Math.cos((lat * Math.PI) / 180)));
  return [
    Number((lon - dLon).toFixed(4)),
    Number((lat - dLat).toFixed(4)),
    Number((lon + dLon).toFixed(4)),
    Number((lat + dLat).toFixed(4)),
  ];
}

